		<h5 class="rules-and-regulations">Team Composition, Roles and Attire</h5>
		<div>
			<p>A team shall have a minimum of five (5) to a maximum of ten (10) participating members in the Men Division. There shall be a minimum of five (5) to a maximum of eight (8) participating members in the Women Division.</p>
			<p>Aside from the required number of members, the team shall be composed of Muse, Captain and Coach/Manager. All team members, including the muse, captain and coach/manager, must not exceed 15 individuals.</p>
			<p>Each team must have its distinctive uniform, color and banner. During the events, every team member is required to wear the following:
				<ul>
					<li>Cowboy shoes, safety shoes or any leather shoes</li>
					<li>polo shirt with buttons</li>
					<li>cowboy hat</li>
				</ul>
			</p>
			<p>Any team member is allowed to compete in as many events as possible provided that they are explicitly indicated in the registration form per event, same as the alternate. <b>Alternate can only play if the designated player cannot play for that day due to injury or some other valid reasons.</b></p>
			<p>The Coach/Manager and/or Team Captain will be responsible for the proper conduct and behavior of the team members on and off the arena during the duration of the rodeo. They must ensure that the Rodeo rules and regulations are strictly complied with within the team.</p>
			<p>The RODEO KING/QUEEN will be selected based on total accumulated points garnered from all events wherein they are a participant.</p>
