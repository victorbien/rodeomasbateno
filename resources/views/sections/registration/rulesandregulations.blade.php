		<h4 class="rules-and-regulations text-uppercase">NON-CATTLE EVENTS</h4>
		<h5 class="rules-and-regulations">Bull Whipping</h5>
		<p><i>(Men and Women)</i></p>
		<div>
			<ul>
				<li>One member/player shall represent the team.</li>
				<li>Each player can use any number of whips, singly or both, or switch from one bullwhip to another as he/she sees it as favorable and seems fit.</li>
				<li>Each player shall be given a maximum of 2 minutes.</li>
				<li>The criteria for judging are as follows:</li>
					<ul>
						<li>Style/Showmanship		-	40%</li>
						<li>Sound					-	40%</li>
						<li>Fluidity of movement	-	20%</li>
					</ul>
			</ul>
		<div>
		<br/><br/>
		<h5 class="rules-and-regulations">Load Carrying</h5>
		<p><i>(Men and Women)</i></p>
		<div>
			<ul>
				<li>A team should have four (4) players.</li>
				<li>Each team is assigned five (5) sacks of sand. A sack weighs 50kg and neatly stacked at the designated point at the start of the event. For women, a sack that weighs 25kg shall be used.</li>
				<li>On the first run, each team member shall carry a sack to a designated point in the arena. Afterward, he/she runs back to his/her teammates and gives his/her cowboy hat to the next member who will carry the next sack. This shall be done until all 5 sacks are carried to the designated point.</li>
				<li>The process shall be repeated by carrying the sacks back to its original place and piling them neatly.</li>
				<li>Judging will be based on the proper piling of the sacks. A penalty/deduction of five (5) seconds shall be given to a team if the sacks are piled improperly and at least one member rearranges the sacks after the team signified completion of the event.</li>
				<li>A demerit on improper piling applies for both designated place and original place. Proper piling means two sacks are on top of another two sacks, with the remaining sack on top of the four sacks.</li>
				<li>If the content of the sack is spilled due to the fault of the carrier, a 5-second penalty shall be imposed. The load will be changed upon reaching the destination if spillage occurs. The time limit of the event is 5 minutes.</li>
				<li>The sole criterion is speed.</li>
			</ul>
