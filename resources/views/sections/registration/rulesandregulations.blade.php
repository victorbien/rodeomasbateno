		<h3 class="rules-and-regulations text-uppercase">Overall Rules and Regulations</h3>
		<div>
			<ul>
				<li>All teams shall compete for the overall championship in the Professional and Student categories. Second and third finishers shall also be declared. The <b>Student Category</b> must have a Men and a Women division and must compete in all its respective events to qualify for the championship.</li>
				<li>In case there is a tie in the overall standing, it shall be broken by a <b>carambola</b> event. Re-computation shall be done to determine the new rankings after the tie-breaking event.</li>
				<li>In any event, the objects to be used shall be assigned to the team by lottery. Drawing of lots shall be made before each event.</li>
				<li>Participants shall present themselves to the Processing then to the Officiating Team (Judges and Timers) at the first call of an event. Any player who fails to show up at the <b>third and final call</b> shall forfeit his participation to the specific event. Forfeiture in a particular event does not mean disqualification in the overall championship.</li>
				<li>A Judge and 3 Timers will be assigned for each competing contestant or team.</li>
				<li>The Judge, with the combination of a whistle and the drop of the right hand with a green and red flag, shall signify and declare the start of the event.</li>
				<li>In a one-person event, once the player is finished, he/she is required to raise to his/her hand. This shall signal the judgement that the team is finished at the specified event.</li>
				<li>In a group event, once the players are finished, at least one member is required to raise his/her hand. This shall signal the judgement that the team is finished at the specified event.</li>
				<li>Any help given to the competing team or contestant from any person or group of people outside the Grand Arena which in a way contributes to the performance of an event (i.e. giving the rope, etc.) will be subject for disqualification or penalty on time. Disqualification or penalty shall only be applicable for the event.</li>
				<li>The decision of the Board of Judges for the specific event is final, provided that no complaints has been filed upon the Appeals Committee. In case a complaint has been raised, it shall and must be filed with the Appeals Committee <b>not later than the end of the event after the event in question</b>. Official complaints forms will be used and shall be available with the Secretariat. It must be signed by the Team Manager/Coach and Captain and shall formally be received by the Appeals Committee.</li>
				<li>The Rodeo Masbateño Inc./VROoM by reason of force majeure, such as lack of animals, darkness, rain and/or inclement weather, can decide to discontinue the events. Team standing will be determined on the events already played.</li>
				<li>All Team Captains, Managers and Members are required to attend the briefing on the rules and regulations. Only the teams that have attended the briefing have the right and shall be allowed to file protests or complaints to the Appeals Committee.</li>
				<li>All team members shall execute a notarized waiver/quitclaim in case of any untoward incident that might occur during the contests. This will be submitted on or before the registration. Non-submission is tantamount to disqualification or non-participation in any of the events.</li>
				<li>A 10-meter lasso with <b>plastic</b> or <b>metal thimbles</b> are allowed. The 4-meter utility rope with an eye is also allowed. Insertion of the end of the four-meter rope into the eye before the event is legal.</li>
				<li>For the Student Category, all players must be bona fide students of the school they are representing. The teams for the Student Category must present Certificate of Registration of the Second Semester of the present Academic Year, duly signed by the School/University Registrar. It shall also contain the official dry seal of the school/university. All participants must bring with them their registration forms of the present semester and their school IDs. Failure to follow the stated requirements shall result to non-participation of a player in any event.</li>
			</ul>
		</div>
