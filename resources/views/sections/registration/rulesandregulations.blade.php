		<h5 class="rules-and-regulations">Bull Riding</h5>
		<div>
			<ul>
				<li>Bull riding is a team event.</li>
				<li>The <b>BULL ROPE</b> and the <b>FLANK STRAP</b> shall be tied by any member of the competing team.</li>
					<ul>
						<li>The <b>bull rope</b> is wrapped around the chest of the animal directly behind the front legs. At the bottom of the rope, a metal bell is hung which is designed to give the rope some weight so that it will fall off the bull as soon as the rider is bucked off or has dismounted from the animal.</li>
						<li>The <b>flank strap</b> is a strap/rope that goes around the flank of the bull. Its purpose is to enhance the natural bucking motion of the bull and to encourage the animal to extend its hind legs while trying to get its rider off its back. Tightly pulling the flank strap will restrict the bull's motion, making the bull uncomfortable. A flank strap is designed for quick release and is removed immediately after the bull exits the arena. The idea behind the flank strap is that it is put on tight enough so that it stays on the bull, yet loose enough so that the bull thinks that he can kick it off, which makes the bull kick.</li>
					</ul>
				<li>Rider is allowed to use spurs provided that the pointed portions of the spurs must rotate (or move).</li>
				<li>The bull rider shall take his ride while the bull is inside the bucking chute. Only one of his hands shall grasp the riding rope when the animal is turned loose. The event shall start as soon as the animal is let loose.</li>
				<li>Team members shall be designated to open the gate of the chute. This shall be done upon a signal from the bull rider is given. Time is not counted on passive resistance of the animal (i.e. animal just walks or does not move at all at the start of the event).</li>
				<li>For a rider to receive a score, he must stay aboard his bull for <b>eight (8) seconds.</b></li>
				<li>A bull rider is <b>disqualified</b> if:</li>
					<ul>
						<li>he touches the bull within the 8-second required time;</li>
						<li>he touches himself with his free hand within the 8-second required time;</li>
						<li>his riding hand comes off from the bull rope at any point during the 8-second required time.</li>
					</ul>
				<li>An automatic re-ride is granted if the abdomen, left flank or right flank of the animal touches the ground, even in split seconds.</li>
				<li>The criteria for judging are as follows:</li>
					<ul>
						<li>Rider (50%)</li>
						<ul>
							<li>Ease of riding					:	+30 points</li>
							<li>Showmanship						:	+10 points</li>
							<li>Attire (cowboy hat, chaps etc)	:	+10 points</li>
						</ul>
						<li>Animal Performance (50%)</li>
						<ul>
							<li>Slow		:	-25 points</li>
							<li>Moderate	:	-20 points</li>
							<li>Semi-wild	:	-15 points</li>
							<li>Wild		:	-10 points</li>
							<li>Very wild	:	less 0 points</li>
						</ul>
					</ul>
			</ul>
