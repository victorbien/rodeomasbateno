		<h3 class="rules-and-regulations text-uppercase">General Rules on the Rodeo Events</h3>
		<h4 class="rules-and-regulations text-uppercase">Cattle Events</h4>
		<h5 class="rules-and-regulations">Cattle Lassoing Wrestling on Foot</h5>
		<p><i>(Men and Women) – One-man play</i></p>
		<div>
			<ul>
				<li>The contestant, equipped with a lariat, must stand in a designated place of the corral.</li>
				<li>The lasso must be properly thrown to catch the animal. The animal must be roped around the neck.</li>
				<li>A limit of <b>three (3)</b> throws is given per player.</li>
				<li>If the animal is accidentally thrown or knocked down without having been wrestled by the player, the animal must be allowed to stand or should be on its feet before it can wrestle again.</li>
				<li>The animal must be properly wrestled to the ground. Three legs should be tied in a fast and effective way.</li>
				<li>The player is disqualified if:</li>	
					<ul>
						<li>the animal is able to stand within the 10-second count of the judge</li>
						<li>the player fails to catch the animal after three throws</li>
						<li>overshoots the time limit:</li>
							<ul>
								<li>three (3) minutes for professional category</li>
								<li>five (5) minutes for the student category</li>
							</ul>
						<li>the following animal's body parts are included in the loop on the third throw:</li>
							<ul>
								<li>one foreleg</li>
								<li>two forelegs</li>
								<li>body</li>
								<li>half-head</li>
								<li>horns</li>
							</ul>
					</ul>
				<li>If the stated animal's body parts are included in the loop on the first and second throw, the player is allowed to remove the rope provided that he/she touches only the rope and not on any parts of the animal's body.</li>
				<li>The sole criterion is speed (100%).</li>
			</ul>
		<div>
		<br/><br/>
		<h5 class="rules-and-regulations">Steer Lassoing on Horseback</h5>
		<p><i>(Women)</i></p>
		<div>
			<ul>
				<li>The player, while on horseback, must be beside the roping chute.</li>
				<li>The lasso must be properly thrown to catch the animal.</li>
				<li>The animal must be roped around the neck (clear neck).</li>
				<li>A <b>limit of three (3)</b> throws is given per player.</li>
				<li>The lasso must be <b>tied to the nearest vertical post under the topmost bar of the corral</b>. The contestant should raise her hand immediately after tying to signify that the event is over.</li>
				<li>The player is disqualified if:</li>	
					<ul>
						<li>she fails to catch the animal after three throws;</li>
						<li>reaches the <b>5-minute</b> time limit;</li>
						<li>the following animal's body parts are included in the loop on the third throw:</li>
							<ul>
								<li>one foreleg</li>
								<li>two forelegs</li>
								<li>body</li>
								<li>half-head</li>
								<li>horns</li>
							</ul>
						<li>the animal was able to get away within 10 seconds after raising her hand.</li>
					</ul>
				<li>If the stated animal's body parts are included in the loop on the first and second throw, the player is allowed to remove the lasso provided that it should not be dismounted and she should not touch the animal.</li>
				<li>The sole criterion is speed.</li>
			</ul>
		<div>
		<br/><br/>
		<h5 class="rules-and-regulations">Steer Wrestling from Horseback</h5>
		<p><i>(Men)</i></p>
		<div>
			<ul>
				<li>The player, while on horseback, must be beside the roping chute.</li>
				<li>The rider/player must catch the steer by dismounting from the horse, whether by jumping or sliding.</li>
				<li>The player must only touch the base of the neck up the head of the steer during the dismount from the horse.</li>
				<li>The rider must touch first and have a good hold on the animal before his foot or feet touches the ground.</li>
				<li>The animal must be properly wrestled to the ground. Three legs should be tied in a fast and effective way.</li>
				<li>The player is disqualified if:</li>	
					<ul>
						<li>he fails to catch the animal</li>
						<li>he falls off the horse before having a good hold of the steer</li>
						<li>his feet or foot touches the ground before having a firm hold on the animal</li>
						<li>he catches the animal and got a hold of any of its parts <b>below the neck</b></li>
						<li>the animal was able to get away from the contestant</li>
						<li>the animal is able to stand within the 10-second count of the judge</li>
						<li>overshoots the time limit:</li>
							<ul>
								<li>three (3) minutes for professional category</li>
								<li>five (5) minutes for the student category</li>
							</ul>
					</ul>
				<li>The sole criterion is speed.</li>
			</ul>
		<div>
		<br/><br/>
		<h5 class="rules-and-regulations">Casting Down</h5>
		<p><i>(Men and Women)</i></p>
		<div>
			<ul>
				<li>A team should have four (4) players.</li>
				<li>The team should catch the animal using their lariats.</li>
				<li>The animal shall be <b>thrown down using a single hitch.</b></li>
				<li>There will be if the following are included in the lasso:</li>
					<ul>
						<li>half of the head</li>
						<li>a horn</li>
						<li>two horns</li>
					</ul>
				<li>Any lasso that goes around or touches the eye or eyes of the animal shall be called a foul lasso and shall not be allowed to be used in casting the animal.</li>
				<li><b>The animal can only be lassoed, hitched and cast down if and only if it is standing on its four legs.</b> There must be at least two lassos on the animal before a hitch can be done.</li>	
				<li>The lead man is allowed to manually restrain the head of the animal if and only if <b>either the left or the right side of the animal's body is on the ground.</b></li>
				<li>As soon as the animal is properly restrained, the head man must show the judge that he is loosening the lasso from the neck of the animal. Otherwise, a penalty shall be given.</li>
				<li>The animal must be properly tied by one or two legmen. All <b>legs must be tied using any methods provided that it shall only use a single 4-meter rope.</b></li>
				<li>Only the front legman is allowed to raise his hand to signify that the event is over. All players must stay at least two meters away from the animal until a judge or the judges order its release.</li>
				<li>The event must be finished within <b>3 minutes for the professional category</b> and <b>5 minutes for the student category</b>. Otherwise, the team shall be disqualified.</li>
				<li>The sole criterion is speed.</li>
			</ul>
		<div>
		<br/><br/>
		<h5 class="rules-and-regulations">Carambola</h5>
		<p><i>(Men and Women – 2-person and 4-person)</i></p>
		<div>
			<ul>
				<li>A team should have two (2) or four (4) players.</li>
				<li>The animal must be caught without the use of any lariat or rope and must be properly restrained and wrestled to the ground.</li>
				<li><b>The event must be finished within 3 minutes for the professional category</b> and <b>5 minutes for the student category</b>. Otherwise, the team shall be disqualified.</li>
				<li>In case that two or more teams catch one animal, <b>the team of the player who first holds or touches the neck owns the animal.</b></li>
				<li><b>If a player hinders a team from wrestling the animal to the ground, or in any way prevents a team from its proper execution of the game, the team that the player belongs to shall be disqualified.</b></li>
				<li>Only the front legman is allowed to raise his hand to signify that the event is over. All players must stay at least two meters away from the animal until a judge or the judges order its release.</li>	
				<li><b>The team is automatically disqualified if the animal is able to stand within the 10-second count of the judge.</b></li>
				<li><b>The event must be finished within 3 minutes for the professional category</b> and <b>5 minutes for the student category</b>. Otherwise, the team shall be disqualified.</li>
				<li>The sole criterion is speed.</li>
			</ul>
