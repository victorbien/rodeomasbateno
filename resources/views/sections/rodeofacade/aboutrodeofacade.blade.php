		<h2 class="section-heading text-uppercase">FACADE DECORATION CONTEST</h2>
	</div>
	<br/><br/>
	<div>
		<h3 class="rules-and-regulations text-uppercase">MECHANICS AND GUIDELINES</h3>
		<h3 class="section-subheading-about-us">As part of the celebration of Rodeo Masbateño 2026 in the Province of Masbate, all business establishments, government offices, and institutions are encouraged to participate in the Facade Decoration Contest to showcase unity, creativity, and support for the annual rodeo festival.</h3>
		
		<br/><br/>
		<h4 class="rules-and-regulations">I. Objectives</h4>
		<div>
			<ol>
				<li>To promote community participation in Rodeo Masbateño 2026.</li>
				<li>To enhance the festive atmosphere of Masbate.</li>
				<li>To showcase creativity, western-themed artistry, and cultural pride.</li>
			</ol>
		<div>
		
		<br/><br/>
		<h4 class="rules-and-regulations">II. Who Can Join</h4>
		<p>The contest is open to:</p>
		<div>
			<ul>
				<li>Business Establishments (malls, stores, banks, restaurants, hotels, etc.)</li>
				<li>Local Government Units (Barangay Halls, City Offices, etc.)</li>
				<li>National Government Agencies</li>
				<li>Government-Owned and Controlled Corporations (GOCCs)</li>
				<li>Private Offices and Institutions</li>
			</ul>
		<div>
		<p>Participants must have a physical establishment located within Masbate City.</p>
		
		<br/><br/>
		<h4 class="rules-and-regulations">III. Theme</h4>
		<p>All facade decorations must align with the official theme of Rodeo Masbateño 2026, highlighting:</p>
		<div>
			<ul>
				<li>Western / Cowboy-inspired designs</li>
				<li>Rodeo Masbateño culture and traditions</li>
				<li>Cattle industry symbolism</li>
				<li>Festive and colorful elements</li>
			</ul>
		<div>
			
		<br/><br/>
		<h4 class="rules-and-regulations">IV. General Guidelines</h4>
		<div>
			<ol>
				<li>Decorations must be displayed on the front facade of the establishment.</li>
				<li>Installation of decorations should be completed on or before APRIL 1, 2026.</li>
				<li>Decorations must remain in place throughout the official duration of Rodeo Masbateño 2026.</li>
				<li>Participants are responsible for the safety and security of their decorations.</li>
				<li>Materials used must be environmentally friendly and compliant with local safety regulations.</li>
				<li>Use of lights and sound effects is allowed, provided they do not cause disturbance or hazard</li>
			</ol>
		<div>
			
		<br/><br/>
		<h4 class="rules-and-regulations">V. Judging Criteria</h4>
		<div>
			<ul>
				<li>Creativity and Originality – 30%</li>
				<li>Relevance to the Theme – 30%</li>
				<li>Visual Impact and Overall Presentation – 25%</li>
				<li>Use of Indigenous / Recyclable Materials – 15%</li>
			</ul>
		<div>
		<p>Total: 100%</p>
		
		<br/><br/>
		<h4 class="rules-and-regulations">VI. How to Join</h4>
		<div>
			<ol>
				<li>Interested participants must confirm their participation through a written confirmation letter.</li>
				<li>The official communication letter from the Rodeo Masbateño Inc. (RMI) Organizing Committee will be distributed on March 9-13, 2026.</li>
				<li>Participants must submit their confirmation by replying to the number provided in the official communication letter.</li>
				<li>A representative from each participating establishment may be required to attend a coordination meeting on <b>March 27, 2026 at Caris Hotel ate exactly 1:00PM.</b></li>
			</ol>
		<div>
			
		<br/><br/>
		<h4 class="rules-and-regulations">VII. Awards and Recognition</h4>
		<div>
			<ul>
				<li>Champion – Php 30,000.00</li>
				<li>1st Runner Up – Php 20,000.00</li>
				<li>2nd Runner Up – Php 10,000.00</li>
			</ul>
		<div>

		<br/><br/>
		<p>Winners will receive plaques of recognition and certificates during the official awarding ceremony of Rodeo Masbateño 2026.</p>
		<p>For inquiries and confirmation submissions, please coordinate with the Rodeo Masbateño 2026 Organizing Committee through the contact details provided in the official letter dated March 27, 2026.</p>
	</div>
