		<h4 class="rules-and-regulations">I. Objectives</h4>
		<p>The 2026 Beef Cooking Competition is one of the major highlights of the 30th Rodeo Festival. It aims to:</p>
		<div>
			<ol>
				<li>Promote beef as the premier agricultural product of Masbate.</li>
				<li>Showcase culinary excellence in preparing either Beef Bulalo or Beef Inasal.</li>
				<li>Preserve traditional cooking methods while encouraging responsible creativity.</li>
				<li>Promote food safety, sanitation, and professional culinary standards.</li>
				<li>Strengthen community participation and celebrate Masbate's rich culinary heritage.</li>
				<li>Provide a platform for chefs, students, and local cooks to demonstrate their skills.</li>
			</ol>
		</div>
		
		<br/><br/>
		<h4 class="rules-and-regulations">II. ELIGIBILITY</h4>
		<div>
			<ol>
				<li>The competition is open to:</li>
					<ul>
						<li>Professional chefs</li>
						<li>Culinary students</li>
						<li>Amateur cooks</li>
						<li>Local food entrepreneurs</li>
					</ul>
				<li>Participation may be:</li>
					<ul>
						<li>Individual (1 cook), or</li>
						<li>Team of two (1 cook and 1 assistant only)</li>
					</ul>
				<li>All contestants must:</li>
					<ul>
						<li>Be at least 18 years old.</li>
						<li>Submit complete registration requirements on or before the deadline.</li>
						<li>Attend the mandatory pre-competition orientation and briefing.</li>
						<li>Agree to abide by all official competition rules.</li>
					</ul>
			</ol>
		</div>
		
		<br/><br/>
		<h4 class="rules-and-regulations">III. COMPETITION FORMAT</h4>
		<p><b>Dish Category (Contestant's Choice)</b></p>
		<p>Each contestant/team must choose and prepare ONLY ONE (1) of the following:</p>
		<div>
			<ul>
				<li>Beef Bulalo, or</li>
				<li>Beef Inasal</li>
			</ul>
		</div>
			
		<p>The chosen category must be declared upon registration and <b>cannot be changed</b> on the day of the competition.</p>
			
		<br/><br/>
		<h4 class="rules-and-regulations">IV. INGREDIENTS AND EQUIPMENT GUIDELINES</h4>
		<p><b>A. Beef Provision</b></p>
		<p>The organizers will provide the official beef according to the chosen category:</p>
		<div>
			<ul>
				<li>Beef shank (for Bulalo), or</li>
				<li>Specified beef cut (for Inasal)</li>
			</ul>
		</div>
		<p>Guidelines:</p>
		<div>
			<ul>
				<li>No substitution or replacement of the provided beef is allowed.</li>
				<li>Beef will be distributed during the official start of the competition.</li>
				<li>Beef will be distributed during the official start of the competition.</li>
			</ul>
		</div>
		<p><b>B. Ingredients</b></p>
		<p>Contestants are responsible for bringing all other ingredients, including:</p>
		<div>
			<ul>
				<li>Vegetables</li>
				<li>Spices and seasonings</li>
				<li>Marinades</li>
				<li>Sauces</li>
				<li>Garnishes</li>
				<li>Accompaniments</li>
			</ul>
		</div>
		<p>Strictly Prohibited:</p>
		<div>
			<ul>
				<li>Pre-cooked beef</li>
				<li>Pre-cooked broth (for Bulalo)</li>
				<li>Pre-grilled beef (for Inasal)</li>
				<li>Pre-prepared sauces or reductions</li>
				<li>Artificial flavor enhancers not declared in the ingredient list</li>
			</ul>
		</div>
			
		<p><b>All seasoning, and cooking must be done within the official competition time, however, due to time constraints, pre-marinated beef may be used.</b></p>

		<p><b>C. Equipment</b></p>
		<p>The organizers will provide ONLY:</p>
		<div>
			<ul>
				<li>Gas tank</li>
				<li>Gas stove</li>
				<li>Preparation table</li>
			</ul>
		</div>
		<p>Contestants must bring:</p>
		<div>
			<ul>
				<li>Knives and chopping boards</li>
				<li>Cooking pots or grill equipment</li>
				<li>Cooking utensils and tools</li>
				<li>Mixing bowls</li>
				<li>Plating materials</li>
				<li>Cleaning materials (cloths, trash bags, etc.)</li>
			</ul>
		</div>
			
		<p>Electrical appliances are discouraged unless previously approved.</p>
		
		<br/><br/>
		<h4 class="rules-and-regulations">V. COOKING TIME AND FLOW</h4>
		<ul>
			<li>15 minutes – Station setup and preparation</li>
			<li>2 hours – Cooking proper</li>
			<li>5 minutes – Final plating</li>
		</ul>
		
		<p>Guidelines:</p>
		<div>
			<ul>
				<li>All cooking must stop immediately when time is called.</li>
				<li>Plating must be completed within the allotted time.</li>
				<li>Late submission will incur penalties.</li>
			</ul>
		</div>
			
		<br/><br/>
		<h4 class="rules-and-regulations">VI. PORTION REQUIREMENTS</h4>
		<p>Each contestant/team must prepare:</p>
		<div>
			<ul>
				<li>Three (3) plated servings for judges; and</li>
				<li>One (1) display plate for documentation and exhibit.</li>
			</ul>
		</div>
		<p>Portions must be equal in size and presentation.</p>
			
		<br/><br/>
		<h4 class="rules-and-regulations">VII. FOOD SAFETY, SANITATION & PROFESSIONAL CONDUCT</h4>
		<p>Strict compliance is required.</p>
		<p>Required Attire:</p>
		<div>
			<ul>
				<li>Chef jacket or proper uniform</li>
				<li>Apron</li>
				<li>Hairnet or chef hat</li>
				<li>Closed, non-slip shoes</li>
			</ul>
		</div>
		<p>Hygiene Rules:</p>
		<div>
			<ul>
				<li>No jewelry during cooking</li>
				<li>Clean fingernails (no nail polish)</li>
				<li>Frequent and proper handwashing</li>
				<li>Proper waste segregation and disposal</li>
				<li>Raw and cooked food must be handled separately</li>
			</ul>
		</div>
		<p>Unprofessional behavior, unsafe food handling, or unsportsmanlike conduct may result in deduction or disqualification.</p>

		<br/><br/>
		<h4 class="rules-and-regulations">VIII. CRITERIA FOR JUDGING (100%)</h4>
		<div>
			<ul>
				<li>Taste & Flavor Balance - 40%</li>
				<li>Authenticity & Cooking Technique - 25%</li>
				<li>Doneness & Texture of Beef - 20%</li>
				<li>Presentation & Plating - 10%</li>
				<li>Hygiene & Work Organization - 5%</li>
			</ul>
		</div>
		<p>Total: 100%</p>
		<br/>
		<p><b>Detailed Description of Criteria</b></p>
		<div>
			<ol>
				<li>Taste & Flavor Balance (40%)</li>
					<ul>
						<li>Depth and richness of broth (Bulalo)</li>
						<li>Balanced seasoning and marinade penetration (Inasal)</li>
						<li>Harmony of flavors</li>
						<li>Overall deliciousness</li>
					</ul>
				<li>Authenticity & Cooking Technique (25%)</li>
					<ul>
						<li>Proper simmering and broth clarity (Bulalo)</li>
						<li>Proper grilling method and basting technique (Inasal)</li>
						<li>Respect for traditional preparation methods</li>
					</ul>
				<li>Doneness & Texture of Beef (20%)</li>
					<ul>
						<li>Tenderness and juiciness</li>
						<li>Proper cooking temperature</li>
						<li>Consistency of texture</li>
					</ul>
					
				<li>Presentation & Plating (10%)</li>
					<ul>
						<li>Clean and attractive presentation</li>
						<li>Proper garnish</li>
						<li>Appropriate serving portion</li>
					</ul>
					
				<li>Hygiene & Work Organization (5%)</li>
					<ul>
						<li>Clean workstation</li>
						<li>Proper handling of ingredients</li>
						<li>Organized workflow</li>
					</ul>
			</ol>
		</div>
		
		<br/><br/>
		<h4 class="rules-and-regulations">IX. SCORING AND TIE-BREAKER RULES</h4>
		<div>
			<ul>
				<li>Each judge will score independently.</li>
				<li>Scores will be tabulated by the Technical Committee.</li>
				<li>The highest total score wins.</li>
			</ul>
		</div>
		<br/>
		<p>In case of a tie:</p>
		<div>
			<ol>
				<li>Higher score in Taste & Flavor Balance prevails.</li>
				<li>If still tied, higher score in Authenticity & Technique prevails.</li>
				<li>Judges deliberate for final decision.</li>
			</ol>
		</div>
		<p><b>The decision of the Board of Judges is FINAL and IRREVOCABLE.</b></p>
		
		<br/><br/>
		<h4 class="rules-and-regulations">X. DEDUCTIONS</h4>
		<div>
			<ul>
				<li>1–5 minutes late submission: -5 points</li>
				<li>6–10 minutes late: -10 points</li>
				<li>Beyond 10 minutes: Disqualification</li>
				<li>Minor unsanitary practice: -1 to -5 points</li>
				<li>Major sanitation violation: Disqualification</li>
				<li>Use of prohibited pre-prepared ingredients: Disqualification</li>
			</ul>
		</div>
			
		<br/><br/>
		<h4 class="rules-and-regulations">XI. REQUIRED DOCUMENTS</h4>
		<p>All contestants must submit:</p>
		<div>
			<ol>
				<li>Accomplished registration form</li>
				<li>Photocopy of valid ID</li>
				<li>Signed waiver</li>
				<li>Complete ingredient list</li>
				<li>Declared chosen category (Bulalo or Beef Inasal)</li>
			</ol>
		</div>
		<p>Incomplete documents may result in disqualification.</p>
			
