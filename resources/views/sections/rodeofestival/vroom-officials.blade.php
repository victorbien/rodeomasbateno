	<br/>
	<div class="">
		<h3 class="section-subheading-vroom text-white">Preserving the Spirit and Standards of the Rodeo Masbateño</h3>
		<p class="text-muted">In the early years of the <b>Rodeo Masbateño</b>, officiating was carried out by the <b>Edwin G. Wagelie Foundation, Inc. (EGWFI)</b>. When the partnership between <b>Rodeo Masbateño Inc. (RMI)</b> and EGWFI officially ended, the <b>Volunteer Rodeo Officials of Masbate (VROoM)</b> took over and continued the work begun by the foundation, ensuring the continuity and integrity of rodeo competitions in Masbate.</p>
	</div>
	<div class="">
		<h3 class="section-subheading-vroom text-white">Foundation and Leadership</h3>
		<p class="text-muted">Established in 2002 by <b>Dr. Nelson Natural (+)</b>, <b>Benjamin Arizala (+)</b>, and <b>Trece Leo R. Gozum</b>, VROoM assumed responsibility for the organization and officiating of rodeo competitions. Dr. Nelson Natural—fondly known as “Doc Nat”—served as the organization’s first <b>Rodeo Director</b>.</p>
		<p class="text-muted">At the same time, <b>Dr. Antonio Aganan (+)</b>, former Station Manager of the Masbate Stockfarm under the Bureau of Animal Industry, led the Rodeo Stockyard. He oversaw the selection, health, and welfare of the cattle used in all rodeo events, reinforcing the organization’s commitment to responsible animal handling.</p>
		<p class="text-muted">Following the passing of Doc Nat and Doc Aga in 2007, leadership of the Rodeo Directorate and stockyard management was entrusted to Trece Leo R. Gozum.</p>
	</div>
	<div class="">
		<h3 class="section-subheading-vroom text-white">Role as Technical Partner</h3>
		<p class="text-muted">Over time, <b>VROoM became the official technical partner of Rodeo Masbateño Inc</b>. Its role expanded beyond officiating, evolving into the <b>technical arm of RMI</b>. Today, VROoM remains active throughout the year, carrying out key responsibilities such as:</p>
	
		<ul class="text-muted">
			<li>Officiating rodeo competitions</li>
			<li>Selection and invitation of participating teams</li>
			<li>Cattle selection and welfare supervision</li>
			<li>Promotion of proper and humane animal handling</li>
		</ul>
	
	</div>
	<div class="">
		<h3 class="section-subheading-vroom text-white">Rules, Regulations, and Animal Welfare</h3>
		<p class="text-muted">The <b>Rodeo Rules and Regulations</b> developed and implemented by VROoM served as a key reference in crafting the <b>Implementing Rules and Regulations (IRR) of Republic Act 8485</b>, also known as the <b>Animal Welfare Act</b>. Notably, VROoM’s own rules are recognized as stricter, reflecting the organization’s strong commitment to ethical practices and animal welfare.</p>
	</div>
	<div class="">
		<h3 class="section-subheading-vroom text-white">Growth and National Recognition</h3>
		<p class="text-muted">As VROoM’s responsibilities expanded, its membership steadily grew, with roles becoming more defined and increasingly focused on ranch-based work. Because of its credibility and professionalism, VROoM members have been invited to officiate and represent in rodeos across different parts of the country.</p>
		<p class="text-muted">Through these efforts, VROoM has become an ambassador of RMI, helping promote and strengthen Masbate’s reputation as the <b>Rodeo Capital of the Philippines</b>. Members regularly travel nationwide to officiate competitions, build connections within the rodeo community, and support the growth of the cattle industry.</p>
	</div>
	<div class="">
		<h3 class="section-subheading-vroom text-white">Service Rooted in Passion and Culture</h3>
		<p class="text-muted">The success of VROoM is driven by the collective dedication of volunteers and Masbateños who serve not for pay or recognition, but out of love for the sport and the thrill of rodeo. Their shared commitment to preserving the rodeo spirit reflects the culture, pride, and identity of Masbate.</p>
