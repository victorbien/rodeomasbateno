				<div class="text-muted">Carambola begins in chaos. As the animal enters the arena, teams rush forward with nothing but their bodies and coordination to rely on. No ropes, no lassos, just hands, timing, and teamwork. The first player to secure the neck claims the animal, and the rest of the team moves in to wrestle it down in a coordinated surge of motion and strength.</div>
				<br/>
				<div class="text-muted">This event strips rodeo to its rawest form. Teams of two or four must restrain the animal and bring it safely to the ground within the time limit, ensuring it cannot stand again within the judge’s count. Precision and communication are critical, as interference or unsafe handling leads to disqualification. Carambola showcases trust between teammates and deep familiarity with animal movement, turning controlled chaos into disciplined action.</div>
