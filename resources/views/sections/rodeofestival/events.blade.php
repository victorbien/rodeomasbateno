				<div class="text-muted">The steer bursts into motion, hooves churning up clouds of dust, as the contestant coils their rope and braces for action. With a swift, precise throw, the lasso lands around the animal’s neck. In one fluid movement, the wrestler brings the steer to the ground and secures three legs, every second measured against the ticking clock. The crowd watches, tense, as skill, strength, and timing merge into a single, decisive moment.</div>
