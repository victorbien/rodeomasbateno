				<div class="text-muted">Using only a lariat or short utility rope, the contestant has three chances to capture the steer and must complete the tie within the allotted time. The animal must remain down until the judge’s count ends, and any misstep, such as failed throws, improper ties, or the steer standing too soon, results in disqualification. On-foot Cattle Wrestling transforms everyday ranch work into a fast-paced test of agility, strategy, and calm precision.</div>
