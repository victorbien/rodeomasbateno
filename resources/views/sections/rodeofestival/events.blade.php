				<div class="text-muted">Four team members line up beside neatly stacked sacks of sand, each weighing as much as a grown person. At the signal, the first carrier hoists a sack onto their shoulder and runs toward the designated point, muscles straining with every step. After dropping the load, they sprint back and hand over a cowboy hat, the signal for the next runner to move. The sequence continues until all sacks are carried out and returned, stacked cleanly once more.</div>
