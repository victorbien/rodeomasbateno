				<h4 class="my-3 text-light">Bull Whipping</h4>
				<div class="text-muted">Bull Whipping fills the arena with sharp cracks that echo off the grandstands, not as an act against an animal, but as a performance of sound and motion. The competitor steps forward alone, whips coiled loosely in hand, then sends them slicing through the air in rhythmic patterns. Each crack is deliberate, controlled, and expressive, drawing cheers from the crowd.</div>
				<br/>
				<div class="text-muted">Despite its name, Bull Whipping does not involve striking bulls or any animals at all. It is a non-cattle event judged purely on technique and artistry. Competitors may use one or multiple bullwhips, switching as needed within the two-minute time limit. Judges score based on sound, fluidity of movement, and showmanship, celebrating the whip as a traditional ranch tool transformed into a display of skill and performance.</div>
