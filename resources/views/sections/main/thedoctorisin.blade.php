	<div class="">
		<p class="text-muted">To know more about rodeo is to know more about animals particularly cows and horses for without these animals, one cannot appreciate the beauty of bull riding, casting down, carambola, lassoing on horseback and on foot and other cattle events.</p>
	</div>
	<div class="">
		<p class="text-muted">Being a veterinarian or a doctor of animals, it is my duty too to educate the people about how to handle animals and more specifically learn the rules and regulations promulgated by our republic for the information, guidance and compliance of all concerned. This is how I got to be called “hayop na doctor”.</p>
	</div>
	<div class="">
		<p class="text-muted">Kidding aside, transporting of animals by sea is common in Masbate, being an island province in which cattle raising for transport to other provinces is one of the major industries.</p>
	</div>
	<div class="">
		<p class="text-muted">Pursuant to the provisions of Republic Act 8485, otherwise known as “The Animal Welfare Act of 1998”, we have to take into consideration the five basic freedoms of animals when transporting animals by sea which are:</p>
		<ul class="text-muted">
			<li>Freedom from thirst, hunger and malnutrition</li>
			<li>Freedom from physical discomfort and pain</li>
			<li>Freedom from injury and disease</li>
			<li>Freedom to conform to essential behaviour patterns</li>
			<li>Freedom from fear and distress</li>
		</ul>
	</div>
	<div class="">
		<p class="text-muted">To promote, ensure and protect the welfare of animals while they are being loaded and unloaded in the ports is our prime objective as animal handlers. In realizing this objective, it is recognized that there are certain limitations during transport that may restrict the enjoyment of the five basic freedoms of animals, provided that such procedures adopted for transportation are not contrary to law.</p>
	</div>
	<div class="">
		<p class="text-muted">This order shall apply to private or public passenger cargo or pure cargo vessels and vehicles authorized to be used to transport animals while within Philippine territory and to companies or persons involved in transporting animals.</p>
	</div>
	<div class="">
		<p class="text-muted">Basic premises and considerations are the following:</p>
		<ul class="text-muted">
			<li>Weather conditions can lengthen the time of stay of animals on board the vessel as well as in the holding area.</li>
			<li>The responsibility of the owner of the animals, shipmaster and other persons-in-charge of overseeing the welfare and protection of the animals are emphasized.</li>
			<li>Good handling and transport management is important to the welfare of the animals carried at sea.</li>
		</ul>
	</div>
	<div class="">
		<p class="text-muted">Before transporting the animals by sea, the shipper shall secure all required documents from the Bureau of Animal Industry (BAI) – Animal Health Division and Animal Welfare Division and in the case of aquatic animals from the Bureau of Fisheries and Aquatic Resources (BFAR) or any other specific animals to appropriate agencies concerned. In no case shall the animals be transported without the valid documents required by BAI and other government agencies concerned or face the consequences for any violation committed.</p>
	</div>
	<div class="">
		<p class="text-muted">As a Veterinary Quarantine Officer, veterinarians like me shall ensure the following once assigned at any port to:</p>
		<ul class="text-muted">
			<li>Ensure that the animals on board are treated humanely, in accordance with R.A. 8485</li>
			<li>Ensure that the animals to be shipped out are healthy and fit to travel.</li>
			<li>Disallow the boarding of sick and/or disabled animals and undertake appropriate measures to address the problem as he deems necessary.</li>
			<li>Brief the livestock shippers as to their responsibilities and as the need arises.</li>
			<li>Ensure that appropriate ramps are available for large animals, cattle and carabaos.</li>
			<li>And ensure that the livestock vans, crates and cages used to transport livestock have proper floorings. They shall have no holes or missing planks.</li>
		</ul>
	</div>
	<div class="">
